using ClosedXML.Excel;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using System.ComponentModel;

namespace AgentWithTools.Tools
{
    public static class ReportTools
    {
        [Description("Generates an Excel spreadsheet containing sample data and saves it to the Desktop.")]
        public static string GenerateSalesExcel(string[] columns, string[][] rows)
        {
            string filePath = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Desktop), "AgentGeneratedReport.xlsx");

            using XLWorkbook workbook = new XLWorkbook();

            IXLWorksheet worksheet = workbook.Worksheets.Add("Report");

            for (int column = 0; column < columns.Length; column++)
                worksheet.Cell(1, column + 1).Value = columns[column];

            for (int row = 0; row < rows.Length; row++)
                for (int column = 0; column < rows[row].Length; column++)
                    worksheet.Cell(row + 2, column + 1).Value = rows[row][column];

            worksheet.Columns().AdjustToContents();
            workbook.SaveAs(filePath);

            return $"Success! Excel file generated at: {filePath}";
        }

        [Description("Generates a PDF document with a corporate title.")]
        public static string GenerateSummaryPdf(
            [Description("Title of the PDF document")] string title)
        {
            string filePath = Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.Desktop),
                "AgentGeneratedDocument.pdf");

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(2, Unit.Centimetre);

                    page.Header()
                        .Text(title)
                        .Bold()
                        .FontSize(18)
                        .FontColor(Colors.Blue.Medium);

                    page.Content()
                        .PaddingVertical(1, Unit.Centimetre)
                        .Text("This document was structured and automatically generated in response to an AI agent request.");

                    page.Footer()
                        .AlignCenter()
                        .Text("Generated by Azure AI Foundry + .NET");
                });
            })
            .GeneratePdf(filePath);

            return $"Success! PDF file generated at: {filePath}";
        }
    }
}
